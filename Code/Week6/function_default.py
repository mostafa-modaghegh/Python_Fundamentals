# ================================
# Default Parameter Value
# مقدار پیش‌فرض برای پارامتر
# ================================

def welcome(name="Student"):
    # اگر مقداری ارسال نشود، مقدار Student استفاده می‌شود
    print(f"Welcome {name}!")

welcome()          # بدون ورودی
welcome("Mostafa") # با ورودی
