# ================================
# Function with Parameters (Arguments)
# تابع با ورودی (پارامتر/آرگومان)
# ================================

def greet(name):
    # این تابع نام دریافت می‌کند و خوش‌آمد می‌گوید
    print("Hello", name)

# گرفتن ورودی از کاربر
user_name = input("Enter your name: ")
greet(user_name)  # ارسال مقدار به تابع
